//! `bench/REPORT.md`: the table, the pick and the per-clip texts.

use std::cmp::Ordering;
use std::fmt::Write;

use whispy_core::audio;
use whispy_core::vad;

use crate::corpus::{Clip, Group};
use crate::measure::{outcome, percentile, Config, Measured, Metrics, Runs};
use crate::memory::LazyUse;
use crate::oracle::{Class, Labels, Recovery};
use crate::v1::V1Results;

/// Criterion 3: share of V1's lost clips holding speech that must come back with text.
const LOST_TARGET: f64 = 0.70;
/// Criterion 4 (transcription part): p95 for a ~5 s sentence.
const SENTENCE_P95_TARGET_S: f64 = 1.5;
/// Criterion 5: memory outside a reprise (peak RSS and physical footprint).
const MEMORY_TARGET_BYTES: u64 = 1_500_000_000;

pub struct MemoryUse {
    pub peak_rss_bytes: u64,
    pub peak_footprint_bytes: u64,
    pub seconds: f64,
    pub characters: usize,
}

pub type MemoryProbe = (Config, Result<MemoryUse, String>);

pub struct Report<'a> {
    clips: &'a [Clip],
    runs: &'a Runs,
    v1: Result<(V1Results, Metrics), String>,
    rows: Vec<(Config, Metrics)>,
    pick: Config,
    pick_meets_guards: bool,
    memory: Vec<MemoryProbe>,
    lazy: Result<LazyUse, String>,
    oracle: Result<Labels, String>,
}

impl<'a> Report<'a> {
    pub fn build(
        clips: &'a [Clip],
        runs: &'a Runs,
        v1: Result<V1Results, String>,
        memory: Vec<MemoryProbe>,
        lazy: Result<LazyUse, String>,
        oracle: Result<Labels, String>,
    ) -> Self {
        let labels = oracle.as_ref().ok();
        let rows: Vec<(Config, Metrics)> = Config::all()
            .into_iter()
            .map(|config| {
                (
                    config,
                    Metrics::from_outcomes(clips, labels, |index| outcome(runs, &config, index)),
                )
            })
            .collect();
        let v1 = v1.map(|results| {
            let metrics =
                Metrics::from_outcomes(clips, labels, |index| v1_outcome(&results, &clips[index]));
            (results, metrics)
        });
        let v1_reference_wer = v1
            .as_ref()
            .ok()
            .map(|(_, metrics)| metrics.wer(Group::Reference));
        let (pick, pick_meets_guards) = choose(&rows, v1_reference_wer);
        Report {
            clips,
            runs,
            v1,
            rows,
            pick,
            pick_meets_guards,
            memory,
            lazy,
            oracle,
        }
    }

    pub fn pick(&self) -> Config {
        self.pick
    }

    fn metrics_of(&self, config: &Config) -> &Metrics {
        &self
            .rows
            .iter()
            .find(|(candidate, _)| candidate == config)
            .expect("every config has a row")
            .1
    }

    pub fn summary(&self) -> String {
        let mut text = String::new();
        if let Ok((_, metrics)) = &self.v1 {
            let _ = writeln!(text, "{}", summary_line("V1 (Python, Parakeet)", metrics));
        }
        for (config, metrics) in &self.rows {
            let _ = writeln!(text, "{}", summary_line(&config.label(), metrics));
        }
        let _ = write!(text, "Pick: {}", self.pick.label());
        text
    }

    pub fn markdown(&self) -> String {
        let mut md = String::new();
        let _ = writeln!(md, "# Whispy V2 bench report\n");
        let _ = writeln!(
            md,
            "Generated by `cargo run --release --bin banc` (from `v2/`) on {} — {}. \
             Every number below is measured by that run; rerun it to refresh this file.\n",
            command_output("date", &["+%Y-%m-%d %H:%M"]),
            machine()
        );
        self.write_corpus(&mut md);
        self.write_oracle(&mut md);
        self.write_table(&mut md);
        self.write_pick(&mut md);
        self.write_criteria(&mut md);
        self.write_lost_clips(&mut md);
        self.write_reference_clips(&mut md);
        md
    }

    fn write_corpus(&self, md: &mut String) {
        let count = |group| self.clips.iter().filter(|clip| clip.group == group).count();
        let _ = writeln!(md, "## Corpus\n");
        let _ = writeln!(md, "| group | clips | what it is |\n|---|---|---|");
        let _ = writeln!(md, "| lost | {} | real dictation chunks V1 returned empty, kept in `~/.whispy/lost/` (no known text) |", count(Group::Lost));
        let _ = writeln!(
            md,
            "| reference | {} | **synthetic voices** (macOS `say`: Thomas, Jacques, Samantha, Daniel; FR and EN; short, ~5 s, long), plus V1's two validation fixtures, all with a known text (`bench/reference/`) |",
            count(Group::Reference)
        );
        let _ = writeln!(md, "| quiet | {} | the short and ~5 s references turned down to RMS 0.012, the level V1's real lost dictations were measured at |", count(Group::Quiet));
        let _ = writeln!(md, "| non-speech | {} | silence, white/brown noise, 50 Hz hum (seeded): any text here is invented |\n", count(Group::NonSpeech));
        let _ = writeln!(
            md,
            "Strategies: **raw** = the clip untouched; **gated** = V1's gates (peak RMS < 0.005, < 0.20 s voiced → nothing) then trim to the voiced span ± 0.3 s; \
             **louder** = gated, and a clip under RMS 0.05 scaled up to it (V1's last retry, applied up front); \
             **padded** = louder, and a clip under 3 s gets 0.5 s of silence on each side. \
             \"A then B\" = engine B transcribes the same prepared input only when A returns nothing.\n"
        );
    }

    fn write_oracle(&self, md: &mut String) {
        let _ = writeln!(md, "## Which lost clips hold speech\n");
        let labels = match &self.oracle {
            Ok(labels) => labels,
            Err(reason) => {
                // The report is committed: no home directory in it.
                let reason =
                    reason.replace(&crate::corpus::bench_dir().display().to_string(), "bench");
                let _ = writeln!(
                    md,
                    "Not classified: {reason}. `banc --labelled` decides criterion 3 on the user's own labels.\n"
                );
                return;
            }
        };
        let lost: Vec<&Clip> = self
            .clips
            .iter()
            .filter(|c| c.group == Group::Lost)
            .collect();
        let count = |class: Class, is_heard: bool| {
            lost.iter()
                .filter_map(|clip| labels.get(&clip.id))
                .filter(|label| label.class == class && label.is_heard == is_heard)
                .count()
        };
        let unlabelled = lost
            .iter()
            .filter(|clip| !labels.contains_key(&clip.id))
            .count();
        let _ = writeln!(
            md,
            "V1 lost breath, clicks and silence too, and no engine should type anything for those. \
             A referee far larger than the shipped engines, **whisper large-v3-turbo** (MLX, run by `bench/oracle.py`, never shipped), \
             decodes each lost clip; a confident French or English utterance (mean token log probability > −0.6, not one of whisper's stock \
             one-liners such as « Thank you. ») is **speech**, a failed decode of a stock one-liner (< −1) is **no speech**, the rest is \
             **doubtful** and left to the user's ear (`bench/oracle/listen.html`, local only); a verdict by ear overrides the oracle.\n"
        );
        let _ = writeln!(md, "| class | by the oracle | by ear |\n|---|---|---|");
        for (class, name) in [
            (Class::Speech, "speech"),
            (Class::Doubtful, "doubtful (not heard yet)"),
            (Class::NoSpeech, "no speech"),
        ] {
            let _ = writeln!(
                md,
                "| {name} | {} | {} |",
                count(class, false),
                count(class, true)
            );
        }
        if unlabelled > 0 {
            let _ = writeln!(
                md,
                "| not in the oracle's output (rerun `bench/oracle.py`) | {unlabelled} | – |"
            );
        }
        let _ = writeln!(
            md,
            "\n\"lost speech\" columns below count only the **speech** clips; \"WER vs oracle\" compares a recovered clip's text with the oracle's, over recovered clips only.\n"
        );
    }

    fn write_table(&self, md: &mut String) {
        let _ = writeln!(md, "## Results\n");
        let _ = writeln!(
            md,
            "| configuration | lost: text | lost speech: text | lost speech: WER vs oracle | reference: WER | reference: text | quiet: WER | quiet: text | non-speech: invented | p50 | p95 | p95, ~5 s sentence |"
        );
        let _ = writeln!(md, "|---|---|---|---|---|---|---|---|---|---|---|---|");
        match &self.v1 {
            Ok((_, metrics)) => {
                let _ = writeln!(
                    md,
                    "{}",
                    table_row("**V1** (Python, Parakeet, full daemon path)", metrics)
                );
            }
            Err(reason) => {
                let _ = writeln!(md, "| **V1** | not measured: {reason} |||||||||||");
            }
        }
        for (config, metrics) in &self.rows {
            let label = if *config == self.pick {
                format!("**{}** (pick)", config.label())
            } else {
                config.label()
            };
            let _ = writeln!(md, "{}", table_row(&label, metrics));
        }
        let _ = writeln!(
            md,
            "\n\"text\" = share of clips that came back non-empty; WER = word errors / reference words, after lowercasing and dropping punctuation; \
             latencies are per clip, model loaded, preparation included, over every speech clip; the last column repeats each ~5 s reference sentence {} times.\n",
            5
        );
    }

    fn write_pick(&self, md: &mut String) {
        let metrics = self.metrics_of(&self.pick);
        let _ = writeln!(md, "## Default engine and strategy (criterion 7)\n");
        let _ = writeln!(
            md,
            "Rule: a configuration that invents text on non-speech is out (it would be typed into the user's window). \
             Among the rest, one whose reference WER is not worse than V1's comes first; then the most lost speech clips with text, \
             the most lost clips with text, the lowest WER over reference and quiet clips, the lowest ~5 s p95.\n"
        );
        if !self.pick_meets_guards {
            let _ = writeln!(md, "**No configuration matches V1's reference WER**; the pick is the best of the others by the same order.\n");
        }
        let _ = writeln!(
            md,
            "**Pick: {}** — lost speech clips with text {}, all lost clips with text {}, reference WER {}, quiet WER {}, invented on non-speech {}, ~5 s sentence p95 {:.2} s.\n",
            self.pick.label(),
            recovery_ratio(&metrics.lost_speech),
            ratio(metrics.non_empty(Group::Lost)),
            percent(metrics.wer(Group::Reference)),
            percent(metrics.wer(Group::Quiet)),
            metrics.non_empty(Group::NonSpeech).0,
            percentile(&metrics.sentence_latencies, 95.0)
        );
        let library = Config::library_default();
        let verdict = if library == self.pick {
            "matches the pick"
        } else {
            "**differs from the pick: update it**"
        };
        let _ = writeln!(
            md,
            "`whispy_core::Pipeline::load_default()` uses `DEFAULT_ENGINE`/`DEFAULT_FALLBACK`/`DEFAULT_STRATEGY` = {}, which {verdict}.\n",
            library.label()
        );
    }

    fn write_criteria(&self, md: &mut String) {
        let metrics = self.metrics_of(&self.pick);
        let _ = writeln!(md, "## Card criteria measured here\n");
        let speech = &metrics.lost_speech;
        if speech.speech_clips > 0 {
            let _ = writeln!(
                md,
                "- **3a, lost clips that hold speech ≥ {:.0}% with text**: {} (WER vs oracle {}) → {}. All lost clips, speech or not: {}.",
                LOST_TARGET * 100.0,
                recovery_ratio(speech),
                percent(speech.wer_against_oracle()),
                if speech.rate() >= LOST_TARGET {
                    "met"
                } else {
                    "**not met**"
                },
                ratio(metrics.non_empty(Group::Lost))
            );
            self.write_doubtful_bound(md, speech);
        } else {
            let _ = writeln!(
                md,
                "- **3a, lost clips that hold speech ≥ {:.0}% with text**: not measured (no oracle labels); all lost clips: {}.",
                LOST_TARGET * 100.0,
                ratio(metrics.non_empty(Group::Lost))
            );
        }
        match &self.v1 {
            Ok((_, v1)) => {
                let _ = writeln!(
                    md,
                    "- **3b, reference WER not worse than V1**: {} against V1's {} → {}.",
                    percent(metrics.wer(Group::Reference)),
                    percent(v1.wer(Group::Reference)),
                    if metrics.wer(Group::Reference) <= v1.wer(Group::Reference) + 1e-9 {
                        "met"
                    } else {
                        "**not met**"
                    }
                );
            }
            Err(reason) => {
                let _ = writeln!(md, "- **3b**: V1 not measured ({reason}).");
            }
        }
        let p95 = percentile(&metrics.sentence_latencies, 95.0);
        let _ = writeln!(
            md,
            "- **4, transcription part**: p95 {:.2} s for a ~5 s sentence (target for the whole release-to-insert path: {SENTENCE_P95_TARGET_S} s; insertion is measured by the app's PR).",
            p95
        );
        self.write_lazy(md);
        let _ = writeln!(md, "Each engine alone, a 180 s dictation in a fresh process (peaks, model load included):\n");
        let _ = writeln!(
            md,
            "| configuration | peak RSS | peak physical footprint | time | characters | both ≤ 1.5 GB |\n|---|---|---|---|---|---|"
        );
        for (config, result) in &self.memory {
            match result {
                Ok(usage) => {
                    let is_within = usage.peak_rss_bytes <= MEMORY_TARGET_BYTES
                        && usage.peak_footprint_bytes <= MEMORY_TARGET_BYTES;
                    let _ = writeln!(
                        md,
                        "| {} | {:.0} MB | {:.0} MB | {:.1} s | {} | {} |",
                        config.label(),
                        usage.peak_rss_bytes as f64 / 1_000_000.0,
                        usage.peak_footprint_bytes as f64 / 1_000_000.0,
                        usage.seconds,
                        usage.characters,
                        if is_within { "yes" } else { "**no**" }
                    );
                }
                Err(reason) => {
                    let _ = writeln!(md, "| {} | failed: {reason} |||||", config.label());
                }
            }
        }
        let _ = writeln!(
            md,
            "\nThe physical footprint is what macOS memory pressure counts, Metal buffers included; RSS alone can miss GPU memory."
        );
        let _ = writeln!(md, "\nFor scale, V1 measured Parakeet at 1476 MB for one 30 s call and 3503 MB for 180 s in one call; V2 splits at 20 s pauses.\n");
    }

    /// Until the user has heard the doubtful clips, 3a rests on the oracle's
    /// sure cases only: say how low it falls if every doubtful clip held speech.
    fn write_doubtful_bound(&self, md: &mut String, speech: &Recovery) {
        let Ok(labels) = &self.oracle else {
            return;
        };
        let (mut doubtful, mut recovered) = (0, 0);
        for (index, clip) in self.clips.iter().enumerate() {
            let is_doubtful = clip.group == Group::Lost
                && labels
                    .get(&clip.id)
                    .is_some_and(|label| label.class == Class::Doubtful);
            if is_doubtful {
                doubtful += 1;
                if !outcome(self.runs, &self.pick, index).text.trim().is_empty() {
                    recovered += 1;
                }
            }
        }
        if doubtful == 0 {
            return;
        }
        let _ = writeln!(
            md,
            "  - {doubtful} doubtful clips not heard yet. If every one held speech, 3a would read {}; the pick returns text on {recovered} of them.",
            ratio((speech.recovered + recovered, speech.speech_clips + doubtful))
        );
    }

    fn write_lazy(&self, md: &mut String) {
        let usage = match &self.lazy {
            Ok(usage) => usage,
            Err(reason) => {
                let _ = writeln!(
                    md,
                    "- **5, memory outside a reprise**: not measured ({reason}).\n"
                );
                return;
            }
        };
        let mb = |bytes: u64| format!("{:.0} MB", bytes as f64 / 1_000_000.0);
        let is_within = usage.normal_peak_rss <= MEMORY_TARGET_BYTES
            && usage.normal_peak_footprint <= MEMORY_TARGET_BYTES
            && !usage.normal_loaded_fallback
            && usage.is_released;
        let _ = writeln!(
            md,
            "- **5, ≤ 1.5 GB outside a reprise**: {} → {}. The default pipeline (`Pipeline::load_default`) loads whisper only when \
             Parakeet returns nothing (a *reprise*) and frees it after {} s unused. Measured in one fresh process: a 180 s dictation, \
             then a ~5 s sentence (`fr-sentence-rapport`) Parakeet is made to miss, twice, then {} s of quiet.\n",
            mb(usage.normal_peak_rss.max(usage.normal_peak_footprint)),
            if is_within { "met" } else { "**not met**" },
            whispy_core::FALLBACK_IDLE.as_secs(),
            whispy_core::FALLBACK_IDLE.as_secs() + 2
        );
        let _ = writeln!(
            md,
            "| phase | peak RSS | peak physical footprint | note |\n|---|---|---|---|"
        );
        let _ = writeln!(
            md,
            "| 180 s dictation, Parakeet only | {} | {} | whisper loaded: {} |",
            mb(usage.normal_peak_rss),
            mb(usage.normal_peak_footprint),
            if usage.normal_loaded_fallback {
                "**yes**"
            } else {
                "no"
            }
        );
        let _ = writeln!(
            md,
            "| reprise (whisper loaded beside Parakeet) | {} | {} | first reprise {:.2} s, next one {:.2} s: loading whisper adds {:.2} s |",
            mb(usage.reprise_peak_rss),
            mb(usage.reprise_peak_footprint),
            usage.cold_reprise_s,
            usage.warm_reprise_s,
            usage.cold_reprise_s - usage.warm_reprise_s
        );
        let _ = writeln!(
            md,
            "| {} s after the last reprise | {} (now) | {} (now) | whisper freed: {} |\n",
            whispy_core::FALLBACK_IDLE.as_secs() + 2,
            mb(usage.released_rss),
            mb(usage.released_footprint),
            if usage.is_released { "yes" } else { "**no**" }
        );
    }

    fn write_lost_clips(&self, md: &mut String) {
        let _ = writeln!(md, "## Lost clips, one by one\n");
        let columns = [
            Config {
                primary: whispy_core::EngineKind::Parakeet,
                fallback: None,
                strategy: whispy_core::Strategy::Louder,
            },
            Config {
                primary: whispy_core::EngineKind::Whisper,
                fallback: None,
                strategy: whispy_core::Strategy::Louder,
            },
        ];
        let _ = writeln!(
            md,
            "| clip | length | peak RMS | voiced | holds speech | V1 | {} | {} | pick |",
            columns[0].label(),
            columns[1].label()
        );
        let _ = writeln!(md, "|---|---|---|---|---|---|---|---|---|");
        for (index, clip) in self
            .clips
            .iter()
            .enumerate()
            .filter(|(_, clip)| clip.group == Group::Lost)
        {
            let span = vad::speech_span(&clip.samples);
            let v1_text = match &self.v1 {
                Ok((results, _)) => v1_outcome(results, clip).text,
                Err(_) => "–".to_string(),
            };
            let _ = writeln!(
                md,
                "| {} | {:.1} s | {:.4} | {:.2} s | {} | {} | {} | {} | {} |",
                clip.id,
                audio::seconds(&clip.samples),
                audio::peak_rms(&clip.samples),
                span.voiced_s,
                self.speech_cell(&clip.id),
                private_cell(&v1_text),
                private_cell(&outcome(self.runs, &columns[0], index).text),
                private_cell(&outcome(self.runs, &columns[1], index).text),
                private_cell(&outcome(self.runs, &self.pick, index).text)
            );
        }
        let _ = writeln!(
            md,
            "\nLost clips are the user's real voice: like V1's log, the report keeps their length, \
             never their text. Set `{SHOW_LOST_TEXT}=1` to read the texts in a local run, and do not commit that report.\n"
        );
    }

    /// The clip's class for the lost-clip table, "(ear)" when the user heard it.
    fn speech_cell(&self, clip_id: &str) -> String {
        let Some(label) = self
            .oracle
            .as_ref()
            .ok()
            .and_then(|labels| labels.get(clip_id))
        else {
            return "–".to_string();
        };
        let class = match label.class {
            Class::Speech => "**speech**",
            Class::Doubtful => "doubtful",
            Class::NoSpeech => "no speech",
        };
        if label.is_heard {
            format!("{class} (ear)")
        } else {
            class.to_string()
        }
    }

    fn write_reference_clips(&self, md: &mut String) {
        let _ = writeln!(md, "## Reference and quiet clips with the pick\n");
        let _ = writeln!(md, "| clip | expected | V1 | pick |\n|---|---|---|---|");
        for (index, clip) in self.clips.iter().enumerate() {
            let Some(expected) = &clip.expected else {
                continue;
            };
            let expected = if expected.is_empty() {
                "(nothing)"
            } else {
                expected.as_str()
            };
            let v1_text = self
                .v1
                .as_ref()
                .map(|(results, _)| v1_outcome(results, clip).text)
                .unwrap_or_default();
            let pick_text = outcome(self.runs, &self.pick, index).text;
            let _ = writeln!(
                md,
                "| {} | {expected} | {} | {} |",
                clip.id,
                cell(&v1_text),
                cell(&pick_text)
            );
        }
    }
}

fn v1_outcome(results: &V1Results, clip: &Clip) -> Measured {
    let entries = results.get(&clip.path).cloned().unwrap_or_default();
    Measured {
        text: entries
            .first()
            .map(|(text, _)| text.clone())
            .unwrap_or_default(),
        seconds: entries.iter().map(|(_, seconds)| *seconds).collect(),
    }
}

/// Returns the pick and whether it also matches V1's reference WER.
///
/// Invented text on non-speech disqualifies: it would be typed into the
/// user's window. Among the rest, a configuration whose reference WER is not
/// worse than V1's is preferred; then the most lost clips with text, the lowest
/// WER over reference and quiet clips, the lowest ~5 s p95.
fn choose(rows: &[(Config, Metrics)], v1_reference_wer: Option<f64>) -> (Config, bool) {
    let matches_v1 = |metrics: &Metrics| {
        v1_reference_wer.is_none_or(|v1| metrics.wer(Group::Reference) <= v1 + 1e-9)
    };
    let order = |a: &&(Config, Metrics), b: &&(Config, Metrics)| -> Ordering {
        matches_v1(&b.1)
            .cmp(&matches_v1(&a.1))
            .then(b.1.lost_speech.rate().total_cmp(&a.1.lost_speech.rate()))
            .then(
                b.1.non_empty_rate(Group::Lost)
                    .total_cmp(&a.1.non_empty_rate(Group::Lost)),
            )
            .then(a.1.combined_wer().total_cmp(&b.1.combined_wer()))
            .then(
                percentile(&a.1.sentence_latencies, 95.0)
                    .total_cmp(&percentile(&b.1.sentence_latencies, 95.0)),
            )
    };
    let honest: Vec<&(Config, Metrics)> = rows
        .iter()
        .filter(|(_, metrics)| metrics.non_empty(Group::NonSpeech).0 == 0)
        .collect();
    let candidates = if honest.is_empty() {
        rows.iter().collect()
    } else {
        honest
    };
    let (config, metrics) = candidates
        .into_iter()
        .min_by(order)
        .expect("at least one configuration");
    (*config, matches_v1(metrics))
}

fn table_row(label: &str, metrics: &Metrics) -> String {
    format!(
        "| {label} | {} | {} | {} | {} | {} | {} | {} | {} | {:.2} s | {:.2} s | {:.2} s |",
        ratio(metrics.non_empty(Group::Lost)),
        recovery_ratio(&metrics.lost_speech),
        if metrics.lost_speech.recovered == 0 {
            "–".to_string()
        } else {
            percent(metrics.lost_speech.wer_against_oracle())
        },
        percent(metrics.wer(Group::Reference)),
        ratio(metrics.non_empty(Group::Reference)),
        percent(metrics.wer(Group::Quiet)),
        ratio(metrics.non_empty(Group::Quiet)),
        metrics.non_empty(Group::NonSpeech).0,
        percentile(&metrics.latencies, 50.0),
        percentile(&metrics.latencies, 95.0),
        percentile(&metrics.sentence_latencies, 95.0)
    )
}

fn summary_line(label: &str, metrics: &Metrics) -> String {
    format!(
        "{label:<36} lost {:>9}  ref WER {:>6}  quiet WER {:>6}  invented {}  p95(5s) {:.2}s",
        ratio(metrics.non_empty(Group::Lost)),
        percent(metrics.wer(Group::Reference)),
        percent(metrics.wer(Group::Quiet)),
        metrics.non_empty(Group::NonSpeech).0,
        percentile(&metrics.sentence_latencies, 95.0)
    )
}

fn ratio((with_text, total): (usize, usize)) -> String {
    if total == 0 {
        return "–".to_string();
    }
    format!(
        "{with_text}/{total} ({:.0}%)",
        100.0 * with_text as f64 / total as f64
    )
}

fn recovery_ratio(recovery: &Recovery) -> String {
    ratio((recovery.recovered, recovery.speech_clips))
}

fn percent(value: f64) -> String {
    format!("{:.1}%", value * 100.0)
}

/// Prints real dictation texts in the lost-clip table instead of word counts.
const SHOW_LOST_TEXT: &str = "WHISPY_BANC_SHOW_LOST_TEXT";

/// A real dictation's transcript as a cell: its word count, or the text when
/// `SHOW_LOST_TEXT` is set; empty shown as –.
fn private_cell(text: &str) -> String {
    let words = text.split_whitespace().count();
    match (words, std::env::var_os(SHOW_LOST_TEXT).is_some()) {
        (0, _) => "–".to_string(),
        (_, true) => cell(text),
        (1, false) => "text (1 word)".to_string(),
        (_, false) => format!("text ({words} words)"),
    }
}

/// A transcript as a table cell: quoted, pipes escaped, empty shown as –.
fn cell(text: &str) -> String {
    if text.trim().is_empty() {
        "–".to_string()
    } else {
        format!("“{}”", text.replace('|', "\\|"))
    }
}

fn command_output(program: &str, args: &[&str]) -> String {
    std::process::Command::new(program)
        .args(args)
        .output()
        .ok()
        .map(|output| String::from_utf8_lossy(&output.stdout).trim().to_string())
        .filter(|text| !text.is_empty())
        .unwrap_or_else(|| "unknown".to_string())
}

fn machine() -> String {
    let memory_gb = command_output("sysctl", &["-n", "hw.memsize"])
        .parse::<f64>()
        .map(|bytes| bytes / 1e9)
        .unwrap_or(0.0);
    format!(
        "{}, {memory_gb:.0} GB",
        command_output("sysctl", &["-n", "machdep.cpu.brand_string"])
    )
}
